// Imports the BLUMA soundtrack (NES-BLUM-FACTORY-ASSETS/music, read-only) as the built-in music library
// (MILESTONES M6: floor 3 songs + 6 SFX; the track has 11 songs + 10 SFX, 4.3 KiB of the 8 KiB SOUND bank).
// Copies the FamiStudio text sources and their ca65 export into engine/audio/ and writes
// src/core/engine-data/audio-library.ts (song and SFX ids in engine order). Run: node scripts/import-sample-music.mjs
import { execFileSync } from 'node:child_process';
import { copyFileSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const assetsRepo = path.resolve(root, '..', 'NES-BLUM-FACTORY-ASSETS');
const music = path.join(assetsRepo, 'music');
const commit = execFileSync('git', ['-C', assetsRepo, 'log', '-1', '--format=%h', '--', 'music'], { encoding: 'utf8' }).trim();
const audio = path.join(root, 'engine', 'audio');

for (const [from, to] of [
  ['src/music.txt', 'src/music.txt'],
  ['src/sfx.txt', 'src/sfx.txt'],
  ['export/music.s', 'music.s'],
  ['export/sfx.s', 'sfx.s'],
]) {
  // committed files stay LF and machine-neutral, as scripts/music/export.mjs writes them
  const text = readFileSync(path.join(music, from), 'utf8').replace(/\r\n/g, '\n').replace(/^; .*[A-Z]:\\.*$/gm, '; (path removed)');
  writeFileSync(path.join(audio, to), text);
}
copyFileSync(path.join(music, 'README.md'), path.join(audio, 'BLUMA-MUSIC-README.md'));

const index = JSON.parse(readFileSync(path.join(music, 'index.json'), 'utf8'));
const songs = [...index.songs].sort((a, b) => a.index - b.index);
const sfx = [...index.sfx].sort((a, b) => a.index - b.index);
songs.forEach((s, i) => {
  if (s.index !== i) throw new Error(`song index gap at ${i}`);
});
sfx.forEach((s, i) => {
  if (s.index !== i) throw new Error(`sfx index gap at ${i}`);
});
if (songs[0].id !== 'title' || songs[1].id !== 'stage' || sfx[0].id !== 'jump' || sfx[1].id !== 'pickup') {
  throw new Error('the M2 ids (songs title/stage, sfx jump/pickup) must keep indexes 0 and 1');
}
const label = (t) => t.replace(/\s*\(.*\)\s*$/, '');
const ts = `// GENERATED by scripts/import-sample-music.mjs from NES-BLUM-FACTORY-ASSETS/music @ ${commit} (BLUMA A4,
// original soundtrack, see ASSETS.md). Order = engine/audio/music.s and sfx.s. Do not edit by hand.

export const MUSIC_SOURCE = 'NES-BLUM-FACTORY-ASSETS/music @ ${commit}';

/** Built-in songs, in the order of engine/audio/music.s. */
export const SONG_LIBRARY = [${songs.map((s) => `'${s.id}'`).join(', ')}] as const;
export type SongId = (typeof SONG_LIBRARY)[number];

/** Built-in SFX, in the order of engine/audio/sfx.s. */
export const SFX_LIBRARY = [${sfx.map((s) => `'${s.id}'`).join(', ')}] as const;
export type SfxId = (typeof SFX_LIBRARY)[number];

/** Songs that play once and stop (jingles), never a stage or boss loop. */
export const ONE_SHOT_SONGS: readonly SongId[] = [${songs.filter((s) => !s.loop).map((s) => `'${s.id}'`).join(', ')}];

/** Titles shown in TABLEAU's music menu. */
export const SONG_TITLES: Record<SongId, string> = {
${songs.map((s) => `  ${s.id}: ${JSON.stringify(label(s.title))},`).join('\n')}
};
`;
writeFileSync(path.join(root, 'src', 'core', 'engine-data', 'audio-library.ts'), ts);
console.log(`music: ${songs.length} songs, ${sfx.length} sfx from ${commit}`);
