/** 8×8 pixel rows for a glyph: background 1, glyph 2, at x=1..5, y=0..6. */
export function glyphPixels(ch: string): Uint8Array {
  const out = new Uint8Array(64).fill(1);
  if (ch === ' ') return out;
  const art = G[ch];
  if (!art) throw new Error(`glyphe absent de la police : « ${ch} »`);
  const rows = art.split(' ');
  if (rows.length !== 7) throw new Error(`glyphe « ${ch} » : ${rows.length} lignes au lieu de 7`);
  rows.forEach((row, y) => {
    if (row.length !== 5) throw new Error(`glyphe « ${ch} » ligne ${y} : ${row.length} colonnes au lieu de 5`);
    for (let x = 0; x < 5; x++) if (row[x] === '#') out[y * 8 + 1 + x] = 2;
  });
  return out;
}

const ACCENT_FOLD: Record<string, string> = {
  é: 'É', è: 'È', ê: 'Ê', ë: 'Ë', à: 'À', â: 'Â', ç: 'Ç', î: 'Î', ï: 'Ï', ô: 'Ô', û: 'Û', ù: 'Ù', ü: 'Ü',
  // typographic punctuation French text uses
  '’': "'", '‘': "'", '“': '«', '”': '»', '–': '-', '—': '-', '…': '...', œ: 'OE', Œ: 'OE', ' ': ' ', ' ': ' ',
};

/** Upper-case + map to glyphs the font has. Unknown characters become spaces (reported by the caller). */
export function foldRomText(text: string): { text: string; unknown: string[] } {
  const unknown: string[] = [];
  let out = '';
  for (const raw of text) {
    // a line break is layout, not a glyph: wrapText starts a new line there (M6)
    if (raw === '\n') {
      out += '\n';
      continue;
    }
    const c = ACCENT_FOLD[raw] ?? raw.toUpperCase();
    if ([...c].every((ch) => FONT_ORDER.includes(ch))) out += c;
    else {
      unknown.push(raw);
      out += ' ';
    }
  }
  return { text: out, unknown };
}
