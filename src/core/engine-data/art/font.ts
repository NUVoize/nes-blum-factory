/** Glyph order in the font bank. Index 0 is the blank HUD tile; digits are contiguous (HUD counters). */
export const FONT_ORDER: readonly string[] = [
  ' ',
  ...'0123456789',
  ...'ABCDEFGHIJKLMNOPQRSTUVWXYZ',
  ...".,!?'-:/+()«»",
  'ÉÈÊËÀÂÇÎÏÔÛÙÜ'.split(''),
].flat();

