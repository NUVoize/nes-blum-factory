export type IconName = keyof typeof ICONS;
export const ICON_NAMES = Object.keys(ICONS) as IconName[];

const PATHS: Record<string, string> = Object.fromEntries(
  Object.entries(ICONS).map(([name, rows]) => [
    name,
    rows.flatMap((row, y) => [...row].flatMap((c, x) => (c === 'X' ? [`M${x} ${y}h1v1h-1z`] : []))).join(''),
  ]),
);

export function PixelIcon({ name, size = 16 }: { name: IconName; size?: number }) {
  return (
    <svg width={size} height={size} viewBox="0 0 16 16" shapeRendering="crispEdges" aria-hidden="true" fill="currentColor">
      <path d={PATHS[name]} />
    </svg>
  );
}
